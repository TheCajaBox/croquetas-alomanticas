    "  #inventario = new Map()",
    "",
    "  guardar(metal, cantidad) {",
    "    if (cantidad <= 0) {",
    "      throw new Error('La cantidad tiene que ser positiva')",
    "    }",
    "    this.#inventario.set(metal, this.cuanto(metal) + cantidad)",
    "  }",
