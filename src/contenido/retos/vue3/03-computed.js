    "",
    "const componente = {",
    "  setup() {",
    "    const colonia = ref([",
    "      { id: 1, nombre: 'Acero', hambre: 80 },",
    "      { id: 2, nombre: 'Bronce', hambre: 20 },",
    "      { id: 3, nombre: 'Peltre', hambre: 95 },",
    "    ])",
    "    const soloHambrientos = ref(false)",
    "",
    "    const visibles = computed(() =>",
    "      soloHambrientos.value ? colonia.value.filter((gato) => gato.hambre > 50) : colonia.value,",
    "    )",
    "",
    "    const resumen = computed(() => `${visibles.value.length} de ${colonia.value.length}`)",
    "",
    "    const alternar = () => {",
    "      soloHambrientos.value = !soloHambrientos.value",
    "    }",
    "",
    "    return { colonia, soloHambrientos, visibles, resumen, alternar }",
    "  },",
    "  template: `",
    "    <div>",
    "      <ul>",
    "        <li v-for=\"gato in visibles\" :key=\"gato.id\">{{ gato.nombre }}</li>",
    "      </ul>",
    "      <p class=\"resumen\">{{ resumen }}</p>",
    "      <button class=\"alternar\" @click=\"alternar\">Cambiar filtro</button>",
    "    </div>",
    "  `,",
    "}",
