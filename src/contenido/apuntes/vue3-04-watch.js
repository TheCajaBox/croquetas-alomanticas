  "",
  "## watch: vigilar algo concreto",
  "",
  "```js",
  "const { ref, watch } = Vue",
  "",
  "const balas = ref(6)",
  "",
  "watch(balas, (nuevo, viejo) => {",
  "  registro.value.push(`de ${viejo} a ${nuevo}`)",
  "})",
  "```",
  "",
  "Le dices **qué** vigilar y **qué hacer**. Recibe el valor nuevo y el viejo, que es",
  "justo lo que hace falta para saber qué ha pasado.",
  "",
  "Y solo se ejecuta **cuando cambia**, no al arrancar. Si quieres que también corra",
  "la primera vez:",
  "",
  "```js",
  "watch(balas, alCambiar, { immediate: true })",
  "```",
  "",
  "Ese `immediate` es la causa de un desconcierto muy típico: en un registro salen dos",
  "apuntes en vez de uno, o algo se ejecuta antes de tiempo. Cuando pase, míralo.",
  "",
  "## Vigilar varias cosas, o algo que no es un ref",
  "",
  "```js",
  "watch([balas, capacidad], ([b, c]) => { ... })",
  "",
  "watch(() => estado.balas, (nuevo) => { ... })       // una propiedad concreta",
  "watch(() => props.gato.id, (nuevo) => { ... })      // una prop",
  "```",
  "",
  "Cuando lo que quieres vigilar no es un `ref` directamente, se envuelve en una",
  "función. Vue la ejecuta para saber qué estás mirando.",
  "",
  "## watchEffect: vigilar lo que toques",
  "",
  "```js",
  "const { watchEffect } = Vue",
  "",
  "watchEffect(() => {",
  "  registro.value.push(`ahora hay ${balas.value}`)",
  "})",
  "```",
  "",
  "No le dices qué vigilar: **lo deduce de lo que leas dentro**. Como es lo mismo que",
  "hace una computada para descubrir sus dependencias, funciona igual de bien.",
  "",
  "Dos diferencias con `watch` que hay que tener claras:",
  "",
  "- **Se ejecuta una vez nada más montar**, sin pedírselo. Es su comportamiento",
  "  normal, no una opción.",
  "- **No recibe el valor viejo.** Solo sabe cómo están las cosas ahora.",
  "",
  "## Cuál usar",
  "",
  "**`watch`** cuando te importa **qué cambió** y de qué a qué, cuando quieres",
  "controlar exactamente qué dispara el efecto, o cuando no quieres que corra al",
  "arrancar. Es el que más se usa.",
  "",
  "**`watchEffect`** cuando el efecto depende de varias cosas y enumerarlas cansa, y",
