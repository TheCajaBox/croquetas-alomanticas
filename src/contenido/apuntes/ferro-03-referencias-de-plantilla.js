  "Casi todo en Vue se hace sin tocar el DOM: cambias un dato y la pantalla se pone al día. Es",
  "la idea entera y funciona el noventa y cinco por ciento del tiempo.",
  "",
  "El cinco por ciento restante son cosas que un dato no puede expresar: poner el foco en un",
  "campo, medir cuánto ocupa algo, hacer scroll hasta abajo, arrancar un `<canvas>`. Para eso",
  "hace falta el elemento de verdad, y se pide con una **referencia de plantilla**.",
  "",
  "## Cómo se pide",
  "",
  "```js",
  "const componente = {",
  "  setup() {",
  "    const caja = ref(null)",
  "",
  "    onMounted(() => {",
  "      caja.value.focus()",
  "    })",
  "",
  "    return { caja }",
  "  },",
  "  template: `<input ref=\"caja\" />`,",
  "}",
  "```",
  "",
  "Tres piezas y las tres hacen falta:",
  "",
  "1. `const caja = ref(null)` — la variable donde Vue lo dejará.",
  "2. `ref=\"caja\"` en la plantilla — el nombre tiene que **coincidir exactamente**.",
  "3. Devolverla, para que la plantilla la vea. (Con `<script setup>` esto sobra.)",
  "",
  "## El momento, que es el reto entero",
  "",
  "`setup` se ejecuta **antes de que exista nada pintado**. En ese momento la referencia vale",
  "`null`, porque el `<input>` todavía no está en ninguna parte:",
  "",
  "```js",
  "setup() {",
  "  const caja = ref(null)",
  "  caja.value.focus()      // TypeError: Cannot read properties of null",
  "}",
  "```",
  "",
  "Vue la rellena justo después de montar. Así que el sitio donde se puede usar es `onMounted`,",
  "o cualquier momento posterior — un manejador de clic, por ejemplo, que por definición ocurre",
  "con la pantalla ya pintada.",
  "",
  "Es exactamente la misma regla que en la mansión Ladrian: lo que toca el DOM va después del",
  "primer pintado.",
  "",
  "## El otro fallo, que es peor porque no avisa",
  "",
  "```js",
  "const caja = ref(null)",
  "// ...",
  "template: `<input ref=\"cajita\" />`",
  "```",
  "",
  "Los nombres no coinciden, así que Vue no rellena nada y `caja.value` se queda en `null`",
  "para siempre. **No hay error, no hay aviso**: simplemente el foco no se pone y no hay",
  "ninguna pista de por qué.",
  "",
  "Cuando una referencia de plantilla «no funciona», lo primero es comprobar la ortografía de",
  "las dos.",
  "",
  "## Referencias dentro de un `v-if`",
  "",
  "```html",
  "<input v-if=\"editando\" ref=\"caja\" />",
  "```",
  "",
  "Mientras `editando` sea falso, el elemento no existe y la referencia vale `null`. Y cuando",
  "lo pongas a verdadero, tampoco vale inmediatamente:",
  "",
  "```js",
  "editando.value = true",
  "caja.value.focus()          // sigue null: todavía no se ha repintado",
  "```",
  "",
  "Hace falta esperar al repintado, que es lo mismo que ya viste con `$nextTick`:",
  "",
  "```js",
  "editando.value = true",
  "await nextTick()",
  "caja.value.focus()",
  "```",
  "",
  "## Con `v-for` sale una lista",
  "",
  "Si pones un `ref` dentro de un bucle, la referencia se llena con **todos** los elementos:",
  "",
  "```html",
  "<li v-for=\"gato in gatos\" ref=\"filas\">{{ gato }}</li>",
  "```",
  "",
