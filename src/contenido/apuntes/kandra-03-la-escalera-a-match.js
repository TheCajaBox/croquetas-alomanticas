  "    return match ($metal) {",
  "        'acero', 'hierro' => 'físico',",
  "        'peltre', 'estaño' => 'aumento',",
  "        default => 'otro',",
  "    };",
  "}",
  "",
  "var_dump(grupoDe('acero'), grupoDe('estaño'), grupoDe('atium'), grupoDe('0'));",
