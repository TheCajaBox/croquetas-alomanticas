  "Seis `if` seguidos comparando la misma variable con seis valores. Cuando un `if` compara",
  "siempre lo mismo, hay una forma de escribirlo que dice justo eso, y se lee como una tabla.",
  "",
  "## `match`",
  "",
  "```php",
  "return match ($metal) {",
  "    'acero', 'hierro' => 'físico',",
  "    'peltre', 'estaño' => 'aumento',",
  "    default => 'desconocido',",
  "};",
  "```",
  "",
  "Tres cosas que hay que saber de él:",
  "",
  "- **Es una expresión**: devuelve un valor. Va con `return` delante y con punto y coma detrás",
  "  de la llave de cierre, que es lo que más despista al principio.",
  "- **Compara con `===`.** Sin conversiones: `'0'` no encaja con `0`, y `match (1)` no entra en",
  "  el caso `true`. Eso lo separa del viejo `switch`, que compara con `==` y da sorpresas.",
  "- **Exige que algo encaje.** Si ningún caso coincide y no hay `default`, lanza un",
  "  `UnhandledMatchError`. Suena molesto y es lo que se quiere: un caso que no habías previsto",
  "  se entera de que existe, en vez de seguir con `null`.",
  "",
  "Los casos que devuelven lo mismo se juntan con comas, y eso es la mitad de lo que hace que",
  "una tabla de seis se lea en tres líneas.",
  "",
  "## `match` frente a `switch`",
  "",
  "`switch` existe desde siempre y sigue funcionando. `match` es mejor en casi todo:",
  "",
  "- compara con `===` en vez de `==`;",
  "- devuelve un valor, así que no hace falta una variable temporal;",
  "- **no se cae de un caso al siguiente**: en `switch`, olvidar el `break` hace que se ejecute",
  "  también lo de abajo, y ese es uno de los errores más antiguos del oficio;",
  "- se queja de lo que no ha previsto.",
  "",
  "El único sitio donde `switch` sigue haciendo falta es cuando un caso necesita varias líneas",
  "de código -`match` solo admite expresiones-. Y si un caso necesita varias líneas, casi",
  "siempre lo que hacía falta era una función con nombre.",
  "",
  "## Cuándo no",
  "",
  "`match` es para comparar **un** valor con una lista. No sirve para condiciones distintas",
  "entre sí:",
  "",
  "```php",
  "if ($edad < 3) { ... }",
  "if ($sacos > 10 && $bruma) { ... }",
  "```",
  "",
  "Eso son condiciones de verdad, no una tabla. Existe la forma `match (true)` para escribirlo",
  "así, y funciona; conviene usarla poco, porque el que lo lea después va a tener que darse",
  "cuenta de que el `true` era un truco.",
  "",
  "Y cuando la tabla es de datos y no de lógica -veinte metales con su grupo-, lo que hacía",
