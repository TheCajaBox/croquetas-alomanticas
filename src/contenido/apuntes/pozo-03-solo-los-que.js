export default codigo(
  "`array_filter` se queda con los elementos que cumplen una condición. La función que le",
  "das devuelve `true` o `false` para cada uno, y **true se queda**.",
  "",
  "```php",
  "$llenos = array_filter($sacos, fn($saco) => $saco > 0);",
  "```",
  "",
  "Fíjate en el orden: aquí la **lista va primera** y la función después, al contrario que",
  "en `array_map`. No hay motivo; es así.",
  "",
  "## La trampa: las claves se quedan donde estaban",
  "",
  "Esto es lo que hay que aprender de este reto, y no se aprende leyéndolo: se aprende",
  "cuando te muerde.",
  "",
  "```php",
  "$sacos = [0, 3, 5];",
  "$llenos = array_filter($sacos, fn($saco) => $saco > 0);",
  "var_dump($llenos);",
  "```",
  "",
  "Sale un array con las claves **1 y 2**. No hay clave 0, porque el elemento que estaba ahí",
  "se ha caído. `array_filter` decide quién se queda, no en qué posición va.",
  "",
  "Y entonces:",
  "",
  "```php",
  "echo $llenos[0];   // Warning: Undefined array key 0",
  "```",
  "",
  "Avisa y sigue con `null`. Ese `null` viaja hacia abajo, se suma a algo, se imprime como",
  "un hueco, y el aviso se pierde entre otros cien. Es de los fallos que llegan a producción.",
  "",
  "## La solución: `array_values`",
  "",
  "```php",
  "$llenos = array_values(array_filter($sacos, fn($saco) => $saco > 0));",
  "```",
  "",
  "`array_values` tira las claves y pone 0, 1, 2… Se lee de dentro hacia fuera: primero se",
  "filtra, y lo que sale se renumera.",
  "",
  "La regla corta: **si el resultado se va a leer por posición, `array_values`**. Si solo se",
  "va a recorrer con `foreach`, a contar con `count` o a pegar con `implode`, da igual y",
  "sobra.",
  "",
  "## Cuando las claves son nombres, es al revés",
  "",
  "Con un array asociativo, conservar las claves es exactamente lo que quieres:",
  "",
  "```php",
  "$inventario = ['acero' => 4, 'oro' => 0, 'peltre' => 2];",
  "$hay = array_filter($inventario, fn($cuantos) => $cuantos > 0);",
  "// ['acero' => 4, 'peltre' => 2]",
  "```",
  "",
  "Aquí `array_values` sería un error: te llevarías los nombres por delante. Por eso el",
  "comportamiento por defecto es conservar, aunque en listas normales moleste.",
  "",
  "## `array_filter` sin función",
  "",
  "Si no le pasas función, se queda con los que cuentan como ciertos:",
  "",
  "```php",
  "array_filter(['a', '', 'b', '0', null]);   // ['a', 'b'], claves 0 y 2",
  "```",
  "",
  "Es cómodo y es peligroso: se lleva el `0` y el `'0'`, que muchas veces son datos buenos.",
  "Cuando lo que quieres es «quita los nulos», dilo: `fn($x) => $x !== null`.",
  "",
  "## Cómo se plantea",
  "",
  "1. Escribe la condición para **un** elemento, en voz alta: «este saco tiene más de cero».",
  "2. Tradúcela: `fn($saco) => $saco > 0`. Solo puede devolver cierto o falso.",
  "3. Pregúntate si el resultado se va a leer por posición. Si sí, `array_values` alrededor.",
  "",
  "## Los casos límite",
  "",
  "- **Nadie cumple**: devuelve un array vacío, no `null` ni `false`.",
  "- **Cumplen todos**: devuelve una copia con las mismas claves.",
  "- **`count` sobre el resultado** funciona igual con claves saltadas: cuenta elementos, no",
  "  posiciones.",
  "",
  "## Pruébalo tú",
  "",
  "```php",
  "<?php",
  "$sacos = [0, 3, 0, 5];",
  "$sin = array_filter($sacos, fn($s) => $s > 0);",
  "$con = array_values($sin);",
  "",
  "var_dump(array_keys($sin));   // las claves con huecos",
  "var_dump(array_keys($con));   // 0, 1",
  "```",
)
