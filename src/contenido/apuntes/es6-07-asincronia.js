  "ese dato, se avisa al usuario? Un programa que solo contempla el camino bueno",
  "funciona hasta el primer día malo.",
  "",
  "Esas dos preguntas son las mismas que se hace cualquiera con oficio delante de",
  "código asíncrono, y no tienen nada que ver con la sintaxis.",
