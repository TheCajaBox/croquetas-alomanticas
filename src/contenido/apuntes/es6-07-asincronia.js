  "```js",
  "async function reunirEquipo() {",
  "  const uno = await avisar('Wax')",
  "  const dos = await avisar('Wayne')",
  "  return [uno, dos]",
  "}",
  "```",
  "",
  "`await` significa «espera aquí a que esto llegue, y dame el valor de dentro». Y",
