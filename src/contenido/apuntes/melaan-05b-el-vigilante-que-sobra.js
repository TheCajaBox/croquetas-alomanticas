  "Ahora hay un sitio donde está la colonia y otro donde está su tamaño, y mantenerlos de",
  "acuerdo es trabajo tuyo. Mientras el único camino sea ese `watch`, bien. En cuanto alguien",
  "cambie la lista de otra manera, o el `watch` no vea el cambio, o llegue un segundo dato",
  "derivado que se olvide de actualizar, los dos sitios dicen cosas distintas.",
  "",
  "Y ahí está lo malo de este fallo: no revienta. Enseña un número viejo, que es un número",
  "perfectamente creíble.",
  "",
  "## El modelo mental: dato o cuenta",
  "",
  "Toda variable de un componente es una de dos cosas:",
  "",
