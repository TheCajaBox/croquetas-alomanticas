  "",
  "```js",
  "const { nombre, alias, recompensa } = ficha",
  "```",
  "",
  "Se lee: «de `ficha`, saca esas tres propiedades y crea una variable con cada",
  "nombre». No es magia ni sintaxis nueva que aprender de memoria: es un espejo. La",
  "izquierda dibuja la forma de la derecha.",
  "",
  "## Con listas es por posición",
  "",
  "```js",
  "const [primero, segundo] = ['Wax', 'Wayne']",
  "```",
  "",
  "En los objetos manda el **nombre**; en las listas, el **orden**. Por eso en un",
  "objeto puedes sacar las propiedades que quieras y en el orden que quieras, y en",
  "una lista tienes que ir por sitios.",
  "",
  "Se pueden saltar posiciones dejando el hueco vacío:",
  "",
  "```js",
  "const [, segundo] = ['Wax', 'Wayne']     // solo el segundo",
  "```",
  "",
  "## Renombrar y poner valores por defecto",
  "",
  "Dos cosas que hacen falta constantemente.",
  "",
  "**Renombrar**, cuando el nombre que trae no te vale (porque ya lo tienes usado, o",
  "porque es malo):",
  "",
  "```js",
  "const { nombre: nombreDelBuscado } = ficha",
  "```",
  "",
  "**Por defecto**, para cuando esa propiedad puede no venir:",
  "",
  "```js",
  "const { recompensa = 0 } = ficha",
  "```",
  "",
