export default codigo(
  "Un `array_reduce` no es magia y no hay que fiarse de él por fe. Se sigue vuelta a vuelta",
  "igual que un bucle, y hacerlo una vez a mano vale más que leer tres explicaciones.",
  "",
  "## La tabla",
  "",
  "Para cualquier `reduce`, la tabla tiene siempre las mismas tres columnas:",
  "",
  "- **`$uno`**: el elemento de esta vuelta. Van en orden, sin saltarse ninguno.",
  "- **`$llevado`**: lo que devolvió la vuelta anterior. En la primera, el valor de partida.",
  "- **devuelve**: lo que sale, y que será el `$llevado` de la siguiente.",
  "",
  "La columna de la derecha se copia a la de en medio, una fila más abajo. Si te fijas en",
  "eso, la tabla se rellena casi sola.",
  "",
  "## Lo que se ve aquí y no en otro sitio",
  "",
  "**El valor de partida cuenta.** Con `10` de partida y la lista `[4, 0, 7]` el total es 21,",
  "no 11. Dar por hecho que un reduce empieza en cero es un fallo que da números plausibles,",
  "y los números plausibles son los que nadie revisa.",
  "",
  "**Una vuelta puede no cambiar nada.** La segunda vuelta suma cero y devuelve lo mismo que",
  "recibió. No es un error: es que ese saco estaba vacío. Un reduce que se queda igual en",
  "una vuelta es normal.",
  "",
  "**El `return` que falta se ve en la tabla.** Si la función se olvidara de devolver, la",
  "columna de la derecha sería `null` y la siguiente fila recibiría `null`. Todo lo acumulado",
  "hasta ahí, perdido. En la tabla salta a la vista; en el código no.",
  "",
  "## Cómo se traza cuando el bucle es largo",
  "",
  "Con tres elementos se hace en un papel. Con trescientos, no, y tampoco hace falta:",
  "",
  "```php",
  "$total = array_reduce($sacos, function ($llevado, $uno) {",
  "    echo \"llevo $llevado, viene $uno\" . PHP_EOL;",
  "    return $llevado + $uno;",
  "}, 0);",
  "```",
  "",
  "Con la forma larga -`function` con llaves- caben dos líneas, y la primera te cuenta cada",
  "vuelta. Es la manera de mirar dentro de cualquier `reduce` que dé un resultado que no",
  "entiendes. Se pone, se lee, se quita.",
  "",
  "## Y cuándo no usar un reduce",
  "",
  "Trazarlo también sirve para decidir eso. Si al seguir la tabla ves que estás llevando dos",
  "cosas a la vez -un total y un nombre, un contador y una lista-, el reduce se va a poner",
  "feo: `$llevado` tendría que ser un array con las dos, y a partir de ahí se lee peor que",
  "un `foreach`. En ese caso, `foreach`. No es un premio usar la función más moderna.",
  "",
  "## Los casos límite",
  "",
  "- **Lista vacía**: cero vueltas, tabla vacía, resultado igual al valor de partida.",
  "- **Un elemento**: una vuelta. Se nota mucho aquí si el valor de partida está mal.",
  "- **Un reduce dentro de otro** es legal y casi siempre ilegible. Si te sale, parte la",
  "  operación en dos funciones con nombre.",
  "",
  "## Pruébalo tú",
  "",
  "```php",
  "<?php",
  "$sacos = [4, 0, 7];",
  "",
  "array_reduce($sacos, function ($llevado, $uno) {",
  "    echo \"llevo $llevado, viene $uno, devuelvo \" . ($llevado + $uno) . PHP_EOL;",
  "    return $llevado + $uno;",
  "}, 10);",
  "```",
)
