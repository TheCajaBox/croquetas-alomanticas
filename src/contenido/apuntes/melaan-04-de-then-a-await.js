import { codigo } from '../retos/comun.js'

export default codigo(
  "Una promesa se puede esperar de dos maneras.",
  "",
  "Con `.then`, encadenando: cada paso recibe el resultado del anterior y devuelve el",
  "siguiente. Cuando un paso necesita algo de **dos pasos atrás**, hay que ir",
  "arrastrando el valor hacia abajo, y ahí es donde se dispara la sangría:",
  "",
  "```js",
  "avisar('Wax').then((uno) =>",
  "  avisar('Wayne').then((dos) =>",
  "    avisar('Marasi').then((tres) => [uno, dos, tres])))",
  "```",
  "",
  "Con `async` y `await`, en línea recta:",
  "",
  "```js",
  "const uno = await avisar('Wax')",
  "const dos = await avisar('Wayne')",
  "const tres = await avisar('Marasi')",
  "return [uno, dos, tres]",
  "```",
  "",
  "Lo mismo, paso a paso, y cada valor se queda a mano en su variable. Con tres pasos",
  "la primera versión ya cuesta; con seis es ilegible, y tiene nombre: **la escalera**.",
  "",
  "## Lo que hay que cambiar",
  "",
  "Tres cosas y ninguna más:",
  "",
  "1. La función lleva `async` delante.",
  "2. Cada `.then(x => ...)` se convierte en `const x = await ...`.",
  "3. El `.catch` se convierte en un `try/catch` alrededor.",
  "",
  "```js",
  "try {",
  "  const uno = await avisar('Wax')",
  "  return uno",
  "} catch (error) {",
  "  return null",
  "}",
  "```",
  "",
  "## Recuerda: async siempre devuelve una promesa",
  "",
  "Aunque tú devuelvas una lista. Quien llame a la función tendrá que esperarla:",
  "",
  "```js",
  "const equipo = reunirEquipo()          // una promesa",
  "const equipo = await reunirEquipo()    // la lista",
  "```",
  "",
  "Es el fallo número uno al convertir, y el síntoma es `Promise { <pending> }` donde",
  "esperabas un dato.",
  "",
  "## Y el que hay que mirar siempre al reescribir",
  "",
  "Convertir una escalera a `await` tiene un riesgo que casi nadie menciona: **es muy",
  "fácil serializar cosas que iban en paralelo**.",
  "",
  "```js",
  "Promise.all([avisar('Wax'), avisar('Wayne')])     // los dos a la vez: 10 ms",
  "",
  "const uno = await avisar('Wax')                   // uno detrás de otro: 20 ms",
  "const dos = await avisar('Wayne')",
  "```",
  "",
  "Si el original lanzaba varias promesas a la vez y tú las conviertes a `await`",
  "seguidos, el código sigue funcionando y tarda el doble. No hay error, no hay test",
  "rojo: solo va más lento, y eso no lo caza nadie hasta que alguien se queja.",
  "",
  "**La pregunta, cada vez que veas dos `await` seguidos: ¿el segundo necesita el",
  "resultado del primero?** Si no, van juntos con `Promise.all`.",
  "",
  "En este reto van en fila a propósito, porque cada aviso depende del anterior. Pero",
  "la pregunta hay que hacérsela siempre.",
  "",
  "## Dónde sigue viviendo .then",
  "",
  "No desaparece del todo, y hay dos sitios donde sigue siendo la forma natural.",
  "",
  "**Cuando no quieres esperar**, solo dejar encargado qué hacer al llegar:",
  "",
  "```js",
  "cargarAjustes().then(aplicar)",
  "```",
  "",
  "**Y en sitios donde no puedes usar `await`**, como el cuerpo de una función que no",
  "es `async`.",
  "",
  "Los dos estilos conviven sin problema. Lo que no conviene es mezclarlos en la",
  "misma función, que se lee fatal.",
  "",
  "## Un aviso sobre await dentro de bucles",
  "",
  "Al reescribir te vas a encontrar con esto:",
  "",
  "```js",
  "for (const id of ids) {",
  "  const ficha = await pedirFicha(id)     // una detrás de otra",
  "  fichas.push(ficha)",
  "}",
  "```",
  "",
  "Con cien identificadores, eso son cien esperas seguidas. Si son independientes:",
  "",
  "```js",
  "const fichas = await Promise.all(ids.map((id) => pedirFicha(id)))",
  "```",
  "",
  "De cien esperas a una. Es el mismo error de serializar, con la forma más común que",
  "tiene en el código real.",
  "",
  "Y la excepción honrada: a veces **quieres** que vayan de una en una, porque el otro",
  "lado no aguanta cien peticiones a la vez. Entonces el bucle está bien y conviene",
  "dejar un comentario diciendo que es a propósito, o alguien lo «arreglará».",
)
