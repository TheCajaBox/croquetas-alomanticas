  "Una consulta que quiera columnas de dos tablas tiene que **unirlas**. La forma es",
  "esta, y son dos piezas nuevas:",
  "",
  "```sql",
  "SELECT p.nombre AS puesto, g.nombre AS gremio",
  "FROM puestos AS p",
  "JOIN gremios AS g",
  "  ON p.gremio_id = g.id;",
  "```",
  "",
  "- **`JOIN`** dice **con qué** se une.",
  "- **`ON`** dice **por dónde**.",
  "",
  "El `ON` no es un filtro, y eso conviene entenderlo bien desde el principio: es la",
  "**costura**. Dice qué fila de aquí va con qué fila de allí, y lo normal es que",
  "compare la clave ajena de una con la clave primaria de la otra.",
  "",
  "## Los alias dejan de ser un lujo",
  "",
  "Las dos tablas tienen una columna que se llama `nombre`. Así que esto no vale:",
  "",
  "```sql",
  "SELECT nombre FROM puestos JOIN gremios ON ...",
  "-- ambiguous column name: nombre",
  "```",
  "",
  "La base se para y lo dice, que es lo mejor que podía pasar. Con la tabla delante,",
  "cada columna sabe de dónde es: `puestos.nombre` y `gremios.nombre`. Y como",
  "escribir el nombre entero de la tabla en cada columna es insoportable, se le pone",
  "un alias corto: `puestos AS p`, y a partir de ahí `p.nombre`.",
  "",
  "La costumbre que merece la pena coger: **pon la tabla delante de todas las",
  "columnas en cuanto haya dos tablas**, incluso de las que no son ambiguas. Cuesta",
  "dos caracteres y evita que la consulta se rompa el día que alguien añada a la otra",
  "tabla una columna que se llame igual.",
  "",
  "## El fallo caro: unir sin decir por dónde",
  "",
