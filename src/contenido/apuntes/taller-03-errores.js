  "Devolver `null` cuando algo va mal parece cómodo y sale caro:",
  "",
  "```js",
  "const restante = retirar(100, 500)   // null",
  "// ...cincuenta líneas después",
  "console.log(restante + 10)           // 10. ¿Y esto de dónde sale?",
  "```",
  "",
  "El problema no es el `null`: es que **el fallo viaja en silencio** y revienta lejos",
  "de donde se produjo. Cuando por fin da la cara, la causa está a cincuenta líneas y",
  "tres funciones de distancia.",
  "",
  "Un error, en cambio, para el programa en el sitio exacto:",
  "",
  "```js",
  "if (cantidad <= 0) {",
  "  throw new Error('La cantidad tiene que ser positiva')",
  "}",
  "```",
  "",
  "`throw` corta la función ahí mismo, como un `return` pero de mala manera: nada de",
  "lo que venga después se ejecuta, y el error **sube** llamada a llamada hasta que",
  "alguien lo recoja o hasta que se acabe el programa.",
  "",
  "## Recogerlo",
  "",
  "```js",
  "try {",
  "  const restante = retirar(saldo, cantidad)",
  "  return { ok: true, saldo: restante }",
  "} catch (error) {",
  "  return { ok: false, error: error.message }",
  "}",
  "```",
  "",
  "En `try` va lo que puede salir mal. Si algo lanza, se salta el resto del `try` y",
  "entra en `catch` con el error entre las manos. `error.message` es el texto que le",
  "pusiste al `new Error(...)`.",
  "",
  "Hay un tercer bloque, `finally`, que se ejecuta pase lo que pase —haya error o",
  "no— y sirve para limpiar: cerrar algo, apagar un indicador de carga.",
  "",
  "```js",
  "try { ... } catch (e) { ... } finally { cargando = false }",
  "```",
  "",
  "## Dónde poner cada cosa",
  "",
  "Esta es la parte que no es sintaxis y sí es criterio, y la que de verdad importa.",
  "",
  "**Lanza en la función que detecta el problema.** Ella sabe qué ha pasado y tiene",
  "el detalle exacto. No lo tapes ahí devolviendo un valor cualquiera.",
  "",
  "**Recoge donde se puede hacer algo al respecto.** Y esa es la clave: no donde el",
  "error ocurre, sino donde alguien puede decidir. Enseñar un aviso, reintentar,",
  "seguir sin ese dato, apuntarlo en un registro. Si en el sitio donde vas a poner el",
  "`catch` no puedes hacer ninguna de esas cosas, no es ahí.",
  "",
  "En la práctica eso significa que la mayoría de las funciones **no** llevan",
  "`try/catch`: dejan pasar el error hacia arriba, y solo lo recoge la capa que sabe",
  "qué hacer con él.",
  "",
  "## El pecado: el catch vacío",
  "",
  "```js",
  "try {",
  "  hacerAlgo()",
  "} catch (error) {",
  "  // ...",
  "}",
  "```",
  "",
  "Eso es peor que no poner nada. Convierte un fallo ruidoso en un fallo silencioso,",
  "y los silenciosos son los que te tienen tres días buscando. El programa sigue como",
  "si nada, con los datos a medias, y el síntoma aparece en otro sitio.",
  "",
  "Si de verdad hay que ignorar un error —pasa, por ejemplo, al leer algo opcional—",
  "que se vea que es a propósito y por qué:",
  "",
  "```js",
  "try {",
  "  ajustes = JSON.parse(guardado)",
  "} catch (error) {",
