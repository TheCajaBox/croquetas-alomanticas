  "",
  "## Las dos formas, y las dos hacen falta",
  "",
  "```php",
  "// La corta, de PHP 8. Es la que se escribe hoy.",
  "class Expedicion",
  "{",
  "    public function __construct(",
  "        public string $nombre,",
  "        public int $sacos,",
  "    ) {}",
  "}",
  "",
  "// La larga. Es la que vas a leer en todo el código que ya existe.",
  "class Expedicion",
  "{",
  "    public string $nombre;",
  "    public int $sacos;",
  "",
  "    public function __construct(string $nombre, int $sacos)",
  "    {",
  "        $this->nombre = $nombre;",
  "        $this->sacos = $sacos;",
  "    }",
  "}",
  "```",
  "",
  "Las dos son idénticas para PHP. La corta se lee de un vistazo; la larga tiene seis sitios",
