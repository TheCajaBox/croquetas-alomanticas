  "",
  "## reactive, el otro",
  "",
  "Hay una segunda forma, para objetos:",
  "",
  "```js",
  "const estado = reactive({ balas: 6, disparos: 0 })",
  "estado.balas -= 1       // sin .value",
  "```",
  "",
  "Se usa menos y tiene una pega gorda que verás en el reto siguiente: si lo",
  "desestructuras, se rompe. La recomendación general —y la que sigue casi todo el",
