  "Vue 3 hace lo mismo que Vue 2. Lo que cambia es dónde se escribe.",
  "",
  "En la casa vieja, cada cosa iba en su cajón: los datos en `data`, los cálculos en",
  "`computed`, las acciones en `methods`. Ordenado, y con una pega: **una misma",
  "funcionalidad quedaba repartida por tres o cuatro cajones**. Para entender cómo",
  "funciona el contador de balas había que mirar en `data`, bajar a `computed`, bajar",
  "a `methods` y volver arriba.",
  "",
  "En un componente de treinta líneas eso es cómodo. En uno de trescientas, con seis",
  "funcionalidades entrelazadas, es un rompecabezas.",
  "",
  "La Composition API le da la vuelta: **todo lo de un asunto, junto**.",
  "",
  "```js",
  "const { ref } = Vue",
  "",
  "const componente = {",
  "  setup() {",
  "    const balas = ref(6)",
  "    const disparar = () => { if (balas.value > 0) balas.value -= 1 }",
  "    const recargar = () => { balas.value = 6 }",
  "",
  "    return { balas, disparar, recargar }",
  "  },",
  "  template: '...',",
  "}",
  "```",
  "",
  "El dato, lo que lo cambia y lo que se calcula con él, en las mismas cinco líneas.",
  "",
  "## setup",
  "",
  "`setup` se ejecuta **una vez**, cuando nace el componente, antes de que exista",
  "pantalla. Lo que devuelvas es lo que la plantilla podrá usar.",
  "",
  "Es una función normal. Dentro puedes declarar variables, escribir funciones, poner",
  "condiciones. Y por eso no hay `this`: no hace falta, porque todo está en el mismo",
  "ámbito. Ese `this` que se perdía y que obligaba a no usar flechas, aquí",
  "simplemente no aparece.",
  "",
  "## ref: el dato que avisa",
  "",
  "Una variable normal no avisa a nadie cuando cambia. `ref` la envuelve en una caja",
  "que sí:",
  "",
  "```js",
  "const balas = ref(6)",
  "```",
  "",
  "`balas` no es 6. Es un objeto con una propiedad `value` que vale 6, y Vue vigila",
  "esa propiedad.",
  "",
  "```js",
  "balas.value          // 6",
  "balas.value -= 1     // así se cambia; Vue se entera",
  "balas -= 1           // esto no tiene sentido: balas es la caja",
  "```",
  "",
  "## El .value, que es lo que más cuesta",
  "",
  "Dentro de `setup`, **siempre `.value`**. Para leer y para escribir.",
  "",
  "En la plantilla, **nunca**: Vue abre la caja por ti.",
  "",
  "```js",
  "setup() {",
  "  const balas = ref(6)",
  "  console.log(balas.value)      // 6",
  "  return { balas }",
  "}",
  "```",
  "",
  "```html",
  "<p>{{ balas }}</p>              <!-- sin .value -->",
  "```",
  "",
  "Esa asimetría es la causa de la mitad de los tropiezos al empezar con Vue 3, y no",
  "hay más remedio que acostumbrarse. El síntoma cuando se olvida es reconocible: en",
  "pantalla sale `[object Object]`, o una comparación que nunca se cumple.",
  "",
  "```js",
  "if (balas > 0)         // siempre verdadero: balas es un objeto",
  "if (balas.value > 0)   // así",
  "```",
  "",
  "## Devolver es hacer público",
  "",
  "Lo que `setup` devuelve es lo que la plantilla ve. Lo que no devuelvas existe",
  "igual, pero es privado del componente:",
  "",
  "```js",
  "setup() {",
  "  const balas = ref(6)",
  "  const capacidad = 6              // no se devuelve: no se pinta",
  "",
  "  const disparar = () => { if (balas.value > 0) balas.value -= 1 }",
  "",
  "  return { balas, disparar }",
  "}",
  "```",
  "",
