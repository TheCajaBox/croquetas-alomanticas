  "",
  "La forma de no equivocarse: recorre la escalera **de fuera hacia dentro** y escribe una",
  "guarda por cada nivel, en ese mismo orden.",
  "",
  "## Cuándo no",
  "",
  "Con dos ramas cortas y simétricas -«si es par, esto; si no, aquello»- un `if`/`else` de",
