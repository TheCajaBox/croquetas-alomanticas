  "",
  "## La cláusula de guarda",
  "",
  "Dale la vuelta: **comprueba primero lo que descarta y sal**.",
  "",
  "```php",
  "// antes",
  "if ($agente !== null) {",
  "    if ($bruma) {",
  "        return 'adelante';",
  "    } else {",
  "        return 'sin bruma no';",
  "    }",
  "} else {",
  "    return 'no hay nadie';",
  "}",
  "",
  "// después",
  "if ($agente === null) {",
  "    return 'no hay nadie';",
  "}",
  "if (!$bruma) {",
  "    return 'sin bruma no';",
  "}",
  "",
  "return 'adelante';",
  "```",
  "",
  "Las dos hacen exactamente lo mismo. La diferencia es que en la segunda, **el camino bueno",
  "está pegado al margen izquierdo** y se lee de un vistazo. Los casos raros están arriba,",
  "cada uno con su respuesta al lado, y se pueden leer de uno en uno sin recordar nada.",
  "",
  "## Por qué desaparecen los `else`",
  "",
  "Porque cada guarda **sale**. Después de un `return` no hay nada que decidir: si el programa",
  "sigue leyendo la línea siguiente, es que la condición no se cumplió. El `else` sobra por",
  "construcción, no por estilo.",
  "",
  "Eso es una regla útil por sí sola: **un `else` con un `return` dentro del `if` es casi",
  "siempre un `else` que se puede borrar**.",
  "",
  "## El orden no se puede cambiar",
  "",
  "Aquí está el único sitio donde este refactor se puede hacer mal sin darse cuenta. Las",
