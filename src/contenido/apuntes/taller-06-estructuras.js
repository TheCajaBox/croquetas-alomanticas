  "**Por qué no `includes` dentro de un bucle:** porque `includes` recorre la lista",
  "entera cada vez. Con cien nombres eso son hasta diez mil comparaciones; un `Set`",
  "lo encuentra directamente, sin recorrer nada.",
  "",
  "Ese es el motivo de verdad para conocerlo. Con veinte elementos da exactamente",
  "igual y no merece la pena cambiar nada. Con diez mil, la diferencia es entre",
