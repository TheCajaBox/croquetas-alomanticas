  "  procesa antes de que exista ninguna.",
  "",
  "## Lo que se gana y lo que se pierde",
  "",
  "**Se gana** que desaparezca el `return`, que era el olvido más común —una variable no",
  "devuelta no existe para la plantilla, y sin ningún error—, y menos ruido alrededor.",
  "",
  "**Se pierde** una cosa: en la forma larga todo lo privado era evidente, porque lo privado",
