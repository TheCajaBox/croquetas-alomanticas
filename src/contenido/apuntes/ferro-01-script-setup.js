  "",
  "## El mismo componente, dos veces",
  "",
  "```js",
  "// La forma larga",
  "export default {",
  "  props: ['dueno'],",
  "  emits: ['recargar'],",
  "  setup(props, { emit }) {",
  "    const balas = ref(6)",
  "    const resumen = computed(() => `${props.dueno}: ${balas.value}`)",
  "    function vaciar() {",
  "      balas.value = 0",
  "      emit('recargar')",
  "    }",
  "    return { balas, resumen, vaciar }",
  "  },",
  "}",
  "```",
  "",
  "```html",
  "<!-- La forma corta -->",
  "<script setup>",
  "const props = defineProps(['dueno'])",
  "const emit = defineEmits(['recargar'])",
  "",
  "const balas = ref(6)",
  "const resumen = computed(() => `${props.dueno}: ${balas.value}`)",
  "function vaciar() {",
  "  balas.value = 0",
  "  emit('recargar')",
  "}",
  "</script>",
  "```",
  "",
  "Tres diferencias, y ninguna cambia lo que el componente hace:",
  "",
  "1. `props:` y `emits:` pasan a ser `defineProps` y `defineEmits`.",
