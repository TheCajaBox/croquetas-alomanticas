  "3. Desaparece el `export default` y la sangría de la función.",
  "",
  "Lo demás es idéntico. `<script setup>` **es** el cuerpo de `setup()`: el compilador lo",
  "envuelve y genera exactamente el componente de arriba.",
  "",
  "## Los `define...` no son funciones",
  "",
  "Esta es la parte que confunde:",
  "",
  "```js",
  "import { defineProps } from 'vue'    // sobra, y da un aviso",
  "```",
  "",
  "`defineProps`, `defineEmits`, `defineExpose` y `defineModel` no se importan porque no",
  "existen en tiempo de ejecución: son **instrucciones para el compilador**, que las reconoce",
  "por el nombre y las sustituye por opciones del componente.",
  "",
  "De ahí salen sus dos limitaciones, que si no se sabe esto parecen arbitrarias:",
  "",
  "- Solo funcionan dentro de `<script setup>`.",
  "- Solo en el nivel de arriba. Nada de meterlos en un `if`, en una función o en un `try`.",
