  "    }",
  "    return sqrt($n);",
  "}",
  "",
  "try {",
  "    echo raiz(9) . PHP_EOL;",
  "    echo raiz(-1) . PHP_EOL;",
  "    echo 'esto no se imprime' . PHP_EOL;",
  "} catch (InvalidArgumentException $error) {",
  "    echo 'me he quejado: ' . $error->getMessage() . PHP_EOL;",
  "} finally {",
  "    echo 'y esto siempre' . PHP_EOL;",
  "}",
  "```",
