  "",
  "## La pareja",
  "",
  "```js",
  "setup() {",
  "  const vueltas = ref(0)",
  "  let reloj = null",
  "",
  "  onMounted(() => {",
  "    reloj = setInterval(() => {",
  "      vueltas.value += 1",
  "    }, 1000)",
  "  })",
  "",
  "  onUnmounted(() => {",
