  "- `addEventListener` en `window` o en `document` → `removeEventListener`",
  "- Observadores (`ResizeObserver`, `IntersectionObserver`, `MutationObserver`) →",
  "  `disconnect()`",
  "- Conexiones abiertas (`WebSocket`, `EventSource`) → `close()`",
