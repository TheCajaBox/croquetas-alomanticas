  "cómo funciona por debajo.",
  "",
  "## Dónde sí y dónde no",
  "",
  "| Dónde | ref | reactive |",
  "|---|---|---|",
  "| En `setup` | `.value` siempre | directo |",
  "| En la plantilla | sin `.value` | directo |",
  "| Dentro de un `reactive` | sin `.value` | directo |",
  "",
  "Esa tercera fila sorprende: un `ref` metido dentro de un objeto reactivo se",
  "desenvuelve solo.",
  "",
  "```js",
  "const balas = ref(6)",
  "const estado = reactive({ balas })",
  "estado.balas          // 6, no el objeto",
  "```",
  "",
