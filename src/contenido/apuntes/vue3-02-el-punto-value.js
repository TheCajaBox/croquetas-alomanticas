  "",
  "```js",
  "const contador = ref(0)",
  "contador.value += 1          // con .value",
  "",
  "const estado = reactive({ balas: 6 })",
  "estado.balas -= 1            // sin .value",
  "```",
  "",
  "Un `ref` **es una caja**: el valor está dentro, en `.value`. Un `reactive` es el",
