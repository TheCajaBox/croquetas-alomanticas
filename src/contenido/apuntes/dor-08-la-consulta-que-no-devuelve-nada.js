  "",
  "## Y lo peor: la versión afirmativa funciona",
  "",
  "```sql",
  "x IN (1, 2, NULL)         -- funciona: le basta con que un trozo sea verdadero",
  "x NOT IN (1, 2, NULL)     -- cero filas, siempre",
  "```",
  "",
  "`IN` se traduce con `OR`, y un `OR` con un verdadero dentro es verdadero aunque haya",
  "desconocidos al lado. Por eso este fallo se cuela tanto: la consulta parecida -la",
