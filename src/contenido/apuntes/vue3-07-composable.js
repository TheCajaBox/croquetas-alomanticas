  "Un composable es **una función que usa la reactividad de Vue y devuelve lo que",
  "hace falta**. Nada más. Ni una clase, ni un sistema de plugins: una función.",
  "",
  "```js",
  "function usarColoniaDeGatos(inicial = []) {",
  "  const colonia = ref([...inicial])",
  "",
  "  const cuantos = computed(() => colonia.value.length)",
  "",
  "  const adoptar = (gato) => { colonia.value = [...colonia.value, gato] }",
  "  const soltar = (id) => { colonia.value = colonia.value.filter((g) => g.id !== id) }",
  "",
  "  return { colonia, cuantos, adoptar, soltar }",
  "}",
  "```",
  "",
  "Y se usa así:",
  "",
  "```js",
  "setup() {",
  "  const { colonia, cuantos, adoptar } = usarColoniaDeGatos()",
  "  return { colonia, cuantos, adoptar }",
  "}",
  "```",
  "",
  "Si esto te suena, es porque **es el cierre de El taller**. Un estado que vive",
  "dentro de una función y unas operaciones que salen para tocarlo. Lo único que",
  "añade Vue es que ese estado es reactivo.",
  "",
  "## Las convenciones",
  "",
  "**El nombre empieza por `usar`** (`use` en inglés). No es obligatorio; es una",
  "señal para quien lee de que esa función usa reactividad y por lo tanto tiene que",
  "llamarse dentro de `setup`.",
  "",
  "**Devuelve un objeto**, no una lista, para que quien lo use pueda coger solo lo que",
  "necesite y renombrar si le conviene.",
  "",
  "**Devuelve refs, no valores.** Si devuelves `colonia.value`, quien lo reciba tendrá",
  "una foto y no se enterará de nada. Otra vez: viaja la caja.",
  "",
  "## Cada llamada, su estado",
  "",
  "```js",
  "const uno = usarColoniaDeGatos()",
  "const otro = usarColoniaDeGatos()",
  "```",
  "",
  "Dos coloniass independientes. Es lo normal y casi siempre lo que quieres: cada",
  "componente que llame al composable tiene lo suyo.",
  "",
  "Si lo que quieres es **una sola colonia compartida** por toda la aplicación, se",
  "saca el estado fuera de la función:",
  "",
  "```js",
  "const colonia = ref([])           // fuera: una sola para todos",
  "",
  "export function usarColoniaDeGatos() {",
  "  const adoptar = (gato) => { ... }",
  "  return { colonia, adoptar }",
  "}",
  "```",
  "",
  "Esa distinción —dentro o fuera de la función— es la diferencia entre estado local y",
  "estado global, y conviene tenerla muy clara porque no se ve a simple vista. Un",
  "composable con estado fuera es, en la práctica, un almacén.",
  "",
  "## Qué se gana",
  "",
  "**Se reutiliza.** El mismo composable en cinco componentes.",
  "",
  "**Se prueba solo.** Es una función: la llamas, tocas lo que devuelve y compruebas.",
  "No hace falta montar ningún componente ni ninguna pantalla.",
  "",
  "**Se lee.** Un `setup` de cinco líneas que llama a tres composables con buenos",
  "nombres cuenta lo que hace el componente mejor que doscientas líneas seguidas.",
  "",
  "**Y se compone**, que es de donde viene el nombre. Un composable puede usar otros:",
  "",
  "```js",
  "function usarRefugio() {",
  "  const { colonia, adoptar } = usarColoniaDeGatos()",
  "  const { croquetas, gastar } = usarEconomia()",
  "",
  "  const alimentar = (gato) => { if (gastar(3)) gato.hambre = 0 }",
  "  return { colonia, croquetas, adoptar, alimentar }",
  "}",
  "```",
  "",
  "## Cómo se diseña uno",
  "",
  "Cuatro preguntas, y son las mismas que para cualquier función bien planteada:",
