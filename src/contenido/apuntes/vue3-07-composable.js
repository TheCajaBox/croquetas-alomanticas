  "**¿Tiene un asunto claro?** Un composable trata de una cosa: la colonia, la",
  "economía, el tamaño de la ventana. Si el nombre necesita una «y», son dos.",
  "",
  "**¿Qué recibe y qué devuelve?** Eso es su contrato, y es lo que debería poder leerse",
  "sin abrirlo. Devolver quince cosas es una señal de que dentro hay más de un asunto.",
  "",
  "**¿Limpia lo que arranca?** Si pone un temporizador o un escuchador, tiene que",
  "apagarlo en `onUnmounted`. Un composable que ensucia y no recoge es peor que no",
  "tenerlo, porque el que lo usa no sabe que tiene que limpiar.",
  "",
  "```js",
  "function usarTamanoDeVentana() {",
  "  const ancho = ref(window.innerWidth)",
  "  const alMedir = () => { ancho.value = window.innerWidth }",
  "",
  "  onMounted(() => window.addEventListener('resize', alMedir))",
  "  onUnmounted(() => window.removeEventListener('resize', alMedir))",
  "",
  "  return { ancho }",
  "}",
  "```",
  "",
  "**¿Se puede usar dos veces en el mismo componente?** Si no, probablemente guarda",
