  "Una función que fabrica objetos ya sabes escribirla. El problema aparece cuando",
  "esos objetos tienen que **hacer** cosas:",
  "",
  "```js",
  "function crearRevolver(capacidad) {",
  "  return {",
  "    balas: capacidad,",
  "    disparar() { ... },      // esta función se crea otra vez",
  "    recargar() { ... },      // ...y esta también, en CADA revólver",
  "  }",
  "}",
  "```",
  "",
  "Con cien revólveres tienes doscientas funciones idénticas ocupando sitio. Una",
  "**clase** separa lo que cambia (los datos) de lo que no (el comportamiento):",
  "",
  "```js",
  "class Revolver {",
  "  constructor(capacidad) {",
  "    this.capacidad = capacidad",
  "    this.balas = capacidad",
  "  }",
  "",
  "  disparar() {",
  "    if (this.balas === 0) return false",
  "    this.balas -= 1",
  "    return true",
  "  }",
  "}",
  "",
  "const arma = new Revolver(6)",
  "arma.disparar()      // true, quedan 5",
  "```",
  "",
  "## Las tres palabras que hay que entender",
  "",
  "**`constructor`** es lo que se ejecuta al hacer `new`. Ahí se colocan los datos",
  "iniciales del objeto. No se llama nunca a mano.",
  "",
  "**`new`** hace cuatro cosas en orden: fabrica un objeto vacío, lo enlaza con la",
  "clase, lo pasa por el constructor con `this` apuntando a él, y te lo devuelve.",
  "Olvidarlo es un clásico y da un error inmediato en las clases modernas.",
  "",
  "**`this`** es «el objeto sobre el que me han llamado». En `arma.disparar()`, `this`",
  "es `arma`. Por eso el mismo método sirve para todos los revólveres del mundo: cada",
  "vez que se ejecuta, `this` es otro.",
  "",
  "## Dónde vive el método de verdad",
  "",
  "Esto explica el ahorro y de paso una cosa que te vas a encontrar.",
  "",
  "Los **datos** viven en cada objeto: cada revólver tiene su `balas`. Los **métodos**",
  "viven una sola vez, en un sitio compartido que se llama el prototipo. Cuando pides",
  "`arma.disparar`, JavaScript lo busca primero en el objeto, no lo encuentra, y sube",
  "a la clase.",
  "",
  "```js",
  "const a = new Revolver(6)",
  "const b = new Revolver(6)",
  "a.disparar === b.disparar     // true: es la misma función",
  "a.balas === b.balas           // valores iguales, pero propiedades distintas",
  "```",
  "",
  "Por eso una clase con mil objetos guarda mil juegos de datos y **un** juego de",
