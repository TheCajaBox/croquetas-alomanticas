  "",
  "Es literalmente `isRef(x) ? x.value : x`. Con eso, dentro de la función da igual qué te",
  "hayan pasado.",
  "",
  "Pero hay una condición, y es la que hace que este reto tenga gracia: **dónde** se llama.",
  "",
  "```js",
  "// Mal: coge el valor una vez y se acabó",
  "function usarDescuento(precio, porcentaje) {",
