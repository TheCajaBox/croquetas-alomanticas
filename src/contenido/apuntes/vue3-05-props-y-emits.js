  "",
  "```js",
  "setup(props, { emit, attrs, slots, expose }) { }",
  "```",
  "",
  "**`props`** es un objeto reactivo con lo que te ha pasado el padre. Se lee",
  "`props.gato`, **sin `.value`** y **nunca con `this`**, que aquí no existe.",
  "",
  "Y no lo desestructures:",
  "",
  "```js",
  "setup({ gato }) { }        // gato deja de actualizarse",
  "```",
  "",
  "Es el mismo problema del `reactive` desestructurado: copias el valor y pierdes la",
  "conexión. Si de verdad quieres desestructurar, `toRefs(props)`.",
  "",
  "## emits, y por qué se declara",
  "",
  "```js",
  "emits: ['adoptar'],",
  "```",
  "",
  "No es obligatorio y conviene ponerlo siempre, por tres razones:",
  "",
  "- **Documenta.** Quien abra el componente ve qué eventos lanza sin buscar los",
  "  `emit` por el cuerpo.",
  "- **Evita un fallo silencioso.** Sin declararlos, un evento con nombre de evento",
  "  nativo se lanza dos veces: la tuya y la del DOM.",
