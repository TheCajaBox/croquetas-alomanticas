  "  },",
  "  emits: ['adoptar'],",
  "",
  "  setup(props, { emit }) {",
  "    const adoptar = () => emit('adoptar', props.gato)",
  "    return { adoptar }",
  "  },",
  "}",
  "```",
  "",
  "## Los dos argumentos de setup",
  "",
  "`setup` recibe dos cosas, y la segunda es un objeto del que se suele sacar solo",
