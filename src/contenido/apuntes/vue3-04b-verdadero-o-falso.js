  "",
  "```js",
  "const filtros = ref({ texto: '', soloActivos: false })",
  "filtros.value.texto = 'wax'",
  "filtros.value = { texto: '', soloActivos: true }    // y esto también vale",
  "```",
  "",
  "Usar `ref` para todo tiene tres ventajas que se notan enseguida: hay **una sola forma** de",
  "trabajar, no se pierde la reactividad al pasar cosas de un lado a otro, y se puede",
  "**reasignar el objeto entero**, que con `reactive` no se puede (`estado = {...}` rompe el",
