  "",
  "## `.value` dentro, nada fuera",
  "",
  "```js",
  "const balas = ref(6)",
  "",
  "balas.value = 5        // dentro de setup: con .value",
  "```",
  "",
  "```html",
  "{{ balas }}            <!-- en la plantilla: sin .value -->",
  "```",
  "",
  "Una `ref` es un objeto con una propiedad `value`; ahí vive el dato. La plantilla desenvuelve",
