  "",
  "La señal de que te lo has dejado:",
  "",
  "```js",
  "console.log(balas + 1)     // '[object Object]1'",
  "```",
  "",
  "Cuando veas un `[object Object]` pegado a algo, busca un `.value` que falta.",
  "",
  "Y el desenvolver de la plantilla es **solo de primer nivel**: si devuelves un objeto con",
  "refs dentro, `{{ objeto.ref }}` no se desenvuelve.",
  "",
  "## Desestructurar un `reactive` corta el cable",
  "",
  "```js",
  "const estado = reactive({ balas: 6 })",
  "const { balas } = estado",
  "",
  "estado.balas = 1",
  "console.log(balas)        // 6",
  "```",
  "",
  "`balas` se llevó una copia del valor de ese momento. La reactividad de `reactive` vive en el",
  "**objeto** —Vue intercepta cuando lees y escribes propiedades suyas— y una variable suelta",
  "ya no pasa por ahí.",
  "",
  "La solución cuando de verdad quieres sacarlo:",
  "",
  "```js",
  "const { balas } = toRefs(estado)",
  "balas.value    // ahora sí, y sigue vinculado",
  "```",
  "",
