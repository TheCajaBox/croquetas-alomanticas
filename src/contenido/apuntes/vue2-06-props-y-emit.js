  "Una pantalla entera en un solo componente no se sostiene. Se parte en piezas, y",
  "las piezas tienen que hablarse. En Vue esa conversación tiene una dirección fija y",
  "conviene entenderla antes que la sintaxis.",
  "",
  "**Los datos bajan. Los avisos suben.**",
  "",
  "El padre le pasa datos al hijo por **props**; el hijo le cuenta al padre que ha",
  "pasado algo por **eventos**. Nunca al revés: un hijo no cambia los datos del padre",
  "directamente.",
  "",
  "## Bajar: props",
  "",
  "En el hijo se declara qué espera recibir:",
  "",
  "```js",
  "props: {",
  "  gato: { type: Object, required: true },",
  "}",
  "```",
  "",
  "Y el padre se los pasa como atributos, con dos puntos porque son valores y no",
  "texto:",
  "",
  "```html",
  "<tarjeta-de-gato :gato=\"gato\" />",
  "```",
  "",
  "Declararlas con tipo y `required` no es burocracia: es **documentación que además",
  "avisa**. Quien abra ese componente sabe qué necesita sin leer el cuerpo, y si",
  "alguien se deja una prop obligatoria, Vue lo dice por consola en vez de fallar",
  "raro más adelante.",
  "",
  "## Las props son de solo lectura",
  "",
  "```js",
  "this.gato.nombre = 'otro'      // funciona y está mal",
  "this.gato = otroGato           // Vue avisa por consola",
  "```",
  "",
  "El dato es del padre. Si el hijo lo cambia, el padre no se entera y las dos copias",
  "dejan de cuadrar; y al siguiente repintado el padre lo machaca con el suyo. El",
  "resultado son esos fallos de «se ha deshecho solo» que no hay quien depure.",
  "",
