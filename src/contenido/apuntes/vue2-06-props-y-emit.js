  "escucha como cualquier otro evento:",
  "",
  "```html",
  "<tarjeta-de-gato :gato=\"gato\" @adoptar=\"adoptar\" />",
  "```",
  "",
  "Y decide él qué hacer. Fíjate en el reparto: el hijo dice **qué ha pasado** —«han",
  "adoptado a este gato»— y el padre decide **qué se hace** al respecto. El hijo no",
  "sabe ni le importa si eso mete el nombre en una lista, lo guarda en un servidor o",
  "las dos cosas.",
  "",
