export default codigo(
  "Una función flecha es otra forma de escribir una función. Más corta, y con una",
  "diferencia de comportamiento que es la razón de verdad por la que existe.",
  "",
  "```js",
  "// las tres son equivalentes",
  "function doble(x) { return x * 2 }",
  "const doble = function (x) { return x * 2 }",
  "const doble = (x) => x * 2",
  "```",
  "",
  "## Las reglas de la forma corta",
  "",
  "**Sin llaves, devuelve solo.** Si el cuerpo es una sola expresión, no hacen falta",
  "ni llaves ni `return`:",
  "",
  "```js",
  "const doble = (x) => x * 2",
  "const doble = (x) => { return x * 2 }    // lo mismo, más largo",
  "```",
  "",
  "**Con un solo parámetro, los paréntesis sobran** (aunque mucha gente los pone",
  "igual, por consistencia):",
  "",
  "```js",
  "const doble = x => x * 2",
  "```",
  "",
  "**Sin parámetros, van vacíos:**",
  "",
  "```js",
  "const ahora = () => Date.now()",
  "```",
  "",
  "**Y para devolver un objeto, hay que envolverlo en paréntesis:**",
  "",
  "```js",
  "const ficha = (nombre) => ({ nombre })     // devuelve el objeto",
  "const roto  = (nombre) => { nombre }       // devuelve undefined",
  "```",
  "",
  "Esta última ya te la has encontrado. Sin los paréntesis, las llaves se",
  "interpretan como el cuerpo de la función.",
  "",
  "## Y ahora lo importante: el this",
  "",
  "Esta es la diferencia que justifica que las flechas existan.",
  "",
  "Una función normal decide **quién es `this` en el momento en que la llamas**, no",
  "donde la escribiste. Y eso se rompe en cuanto la función viaja:",
  "",
  "```js",
  "const timbre = {",
  "  veces: 0,",
  "  sonar: function () {",
  "    this.veces += 1        // aquí this es... depende de cómo se llame",
  "  },",
  "}",
  "",
  "timbre.sonar()             // bien: this es timbre",
  "const suelta = timbre.sonar",
  "suelta()                   // mal: this ya no es timbre",
  "```",
  "",
  "Al hacer `timbre.sonar()`, JavaScript mira lo que hay a la izquierda del punto y",
  "ese es el `this`. Al llamar `suelta()` no hay nada a la izquierda de nada, así que",
  "`this` no es el timbre. En un módulo, es `undefined`, y el error que sale es",
  "`Cannot read properties of undefined (reading 'veces')`.",
  "",
  "**Una función flecha no tiene `this` propio.** Usa el del sitio donde la",
  "escribiste, y eso ya no cambia por mucho que la pasees:",
  "",
  "```js",
  "const timbre = {",
  "  veces: 0,",
  "  arrancar() {",
  "    setTimeout(() => {",
  "      this.veces += 1      // this sigue siendo timbre",
  "    }, 100)",
  "  },",
  "}",
  "```",
  "",
  "Ese es el caso de uso principal: **funciones que se pasan a otro sitio y se",
  "llaman más tarde**. Temporizadores, escuchadores de eventos, `map` y `filter`.",
  "",
  "## Cuándo NO usar una flecha",
  "",
  "Justo por lo mismo. Como no tiene `this` propio, no sirve para ser un método que",
  "necesite `this`:",
  "",
  "```js",
  "const timbre = {",
  "  veces: 0,",
  "  sonar: () => {",
  "    this.veces += 1        // this NO es timbre; aquí no funciona",
  "  },",
  "}",
  "```",
  "",
  "Es el error inverso, y da la misma clase de dolor de cabeza.",
  "",
  "La regla práctica, y sirve casi siempre:",
  "",
  "- **Método de un objeto o de una clase** → función normal (o la forma corta",
  "  `sonar() { ... }`).",
  "- **Función que le pasas a otra función** → flecha.",
  "",
  "En Vue 3 esto casi desaparece, porque en `setup` no se usa `this` para nada. En",
  "Vue 2 y en las clases, importa mucho.",
  "",
  "## El otro detalle: no se elevan",
  "",
  "Las funciones declaradas con `function` se pueden llamar antes de escribirlas.",
  "Las flechas, no, porque son variables:",
  "",
  "```js",
  "saludar()                            // funciona",
  "function saludar() { }",
  "",
  "saludar()                            // error",
  "const saludar = () => { }",
  "```",
  "",
  "No es un problema si mantienes la costumbre de declarar antes de usar, que es",
  "buena por otras razones.",
  "",
  "## Y una cosa que la gente exagera",
  "",
  "Verás quien escribe todo con flechas por sistema, incluidas funciones de",
  "cincuenta líneas guardadas en un `const`. Funciona, y se pierde algo: una función",
  "declarada con `function` sale con su nombre en los mensajes de error y en las",
  "trazas de la pila, y una anónima guardada en una variable a veces no.",
  "",
  "No es una guerra que merezca la pena librar. Lo que sí conviene es ser",
  "consistente dentro de un mismo proyecto, porque la mezcla arbitraria es lo que de",
  "verdad cansa al leer.",
)
