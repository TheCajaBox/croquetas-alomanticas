import { codigo } from '../retos/comun.js'

export default codigo(
  "Con dos o tres niveles, pasar props funciona muy bien. Con seis, un dato que nace",
  "arriba y se usa abajo obliga a que **todos los de en medio lo reciban y lo pasen**",
  "sin usarlo para nada.",
  "",
  "A eso se le llama perforar props, y es incómodo por tres razones: hay que tocar",
  "componentes que no tienen nada que ver, sus firmas mienten sobre lo que necesitan,",
  "y añadir un dato nuevo obliga a repetir la operación entera.",
  "",
  "## La salida",
  "",
  "```js",
  "// arriba",
  "const colonia = ref([...])",
  "provide(CLAVE_COLONIA, colonia)",
  "",
  "// abajo, a la profundidad que sea",
  "const colonia = inject(CLAVE_COLONIA)",
  "```",
  "",
  "Cualquier descendiente puede pedirlo, sin que los de en medio se enteren.",
  "",
  "## Comparte la caja, no el valor",
  "",
  "El fallo número uno:",
  "",
  "```js",
  "provide(CLAVE_COLONIA, colonia)          // bien: el ref entero",
  "provide(CLAVE_COLONIA, colonia.value)    // mal: una foto del momento",
  "```",
  "",
  "Con `.value` compartes el contenido en ese instante. El nieto se queda con una",
  "copia congelada y no se entera de ningún cambio posterior.",
  "",
  "Es otra vez lo mismo: lo que viaja tiene que ser la caja, no lo de dentro.",
  "",
  "## La clave, con Symbol",
  "",
  "```js",
  "export const CLAVE_COLONIA = Symbol('colonia')",
  "```",
  "",
  "Se puede usar un texto, y con un `Symbol` exportado se gana bastante: no hay",
  "colisiones con otra clave que se llame igual, el editor te autocompleta, y quien",
  "lea el `inject` puede ir al origen de un salto.",
  "",
  "Con texto suelto, `inject('colonia')` obliga a buscar a mano quién lo provee, y no",
  "hay nada que avise si te equivocas al escribirlo.",
  "",
  "## Valor por defecto",
  "",
  "```js",
  "const colonia = inject(CLAVE_COLONIA, ref([]))",
  "```",
  "",
  "Si nadie lo provee, `inject` devuelve `undefined` y el componente revienta al",
  "usarlo. Con un valor por defecto, funciona igual aunque se use suelto —cosa que",
  "pasa constantemente en los tests.",
  "",
  "## Quién puede escribir",
  "",
  "Aquí está la decisión de diseño, y es la que más problemas evita.",
  "",
  "Si compartes un `ref`, **cualquier descendiente puede escribirlo**. Eso parece",
  "cómodo y es exactamente la situación que hace imposible saber quién cambió qué.",
  "",
  "Lo recomendable es compartir el dato **de solo lectura** y las funciones que lo",
  "modifican:",
  "",
  "```js",
  "provide(CLAVE_COLONIA, {",
  "  colonia: readonly(colonia),",
  "  adoptar,",
  "  soltar,",
  "})",
  "```",
  "",
  "Ahora los cambios pasan por dos funciones con nombre, que se pueden buscar, leer y",
  "probar. Y `readonly` avisa por consola si alguien intenta escribir directamente.",
  "",
  "Es la misma idea del cierre de El taller: el estado dentro, y solo salen las",
  "operaciones que tú decides. Vue no la inventa; le pone sintaxis.",
  "",
  "## Cuándo usarlo y cuándo no",
  "",
  "`provide`/`inject` está bien para lo que es **de todo un subárbol** y cambia poco:",
  "el tema visual, el idioma, el usuario conectado, la configuración.",
  "",
  "**No** es un sustituto de las props para lo normal. Tiene un coste real: crea una",
  "dependencia invisible. Un componente con `inject` no se puede montar en cualquier",
  "sitio —necesita un ancestro que lo provea— y eso no se ve en su firma. Con props,",
  "lo que necesita está escrito.",
  "",
  "La regla práctica: **props por defecto; `provide`/`inject` cuando la alternativa es",
  "atravesar tres niveles o más con un dato que esos niveles no usan.**",
  "",
  "Y para el estado de toda la aplicación —el que sobrevive a cambiar de pantalla— lo",
  "que se usa es un almacén tipo Pinia, que resuelve lo mismo con herramientas para",
  "depurar y con un sitio único donde mirar.",
)
