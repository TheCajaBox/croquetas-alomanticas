  "",
  "## Cuándo migrar y cuándo no",
  "",
  "Que exista una forma nueva no obliga a nada.",
  "",
  "**Migra** cuando el componente sea grande y difícil de seguir, cuando tengas que",
  "compartir lógica entre varios, o cuando ya vas a tocarlo por otro motivo.",
  "",
  "**No migres** un componente de treinta líneas que funciona y nadie toca. La",
  "Options API no está obsoleta: sigue soportada en Vue 3 y para componentes",
  "pequeños se lee perfectamente. Migrar por moda es coste sin beneficio.",
  "",
  "Y sobre todo: **no hace falta migrar todo un proyecto de golpe**. Las dos formas",
  "conviven en la misma aplicación sin problema. La estrategia sensata es la de",
