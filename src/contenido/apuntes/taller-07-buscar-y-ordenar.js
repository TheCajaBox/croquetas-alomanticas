  "## Buscar uno",
  "",
  "```js",
  "casos.find((caso) => caso.titulo === 'Bleeder')     // el objeto, o undefined",
  "casos.findIndex((caso) => caso.recompensa > 1000)   // la posición, o -1",
  "```",
  "",
  "`find` **para en cuanto encuentra el primero**: no recorre la lista entera si no",
