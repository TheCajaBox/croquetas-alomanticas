  "correcto: «todos los casos de una lista sin casos están asignados» no es mentira,",
  "y «alguno lo está» sí lo sería. A esto se le llama verdad vacua, y es motivo de",
  "sorpresa una vez en la vida de cada programador — normalmente cuando una validación",
  "deja pasar una lista vacía.",
  "",
  "## Ordenar, que es donde está la trampa",
  "",
  "**Trampa uno: `sort` estropea tu lista.** No devuelve una lista nueva: reordena la",
  "que le des, y encima te la devuelve, así que parece que hizo una copia.",
  "",
  "```js",
  "const ordenados = casos.sort(...)      // casos también quedó ordenado",
  "const ordenados = [...casos].sort(...) // así no",
  "```",
  "",
  "**Trampa dos: por defecto ordena como texto.**",
  "",
  "```js",
  "[10, 9, 100].sort()      // [10, 100, 9]  ¡como en un diccionario!",
