  "Tres `foreach` con su acumulador a mano: uno transforma, uno filtra y uno suma. Los tres",
  "funcionan y los tres tienen el mismo sitio donde equivocarse -el acumulador declarado dentro",
  "del bucle en vez de fuera- y el mismo ruido alrededor.",
  "",
  "## Reconocer cuál es cuál",
  "",
  "Se distinguen mirando **qué le pasa al acumulador**:",
  "",
  "| Dentro del bucle | Es un… |",
  "|---|---|",
  "| `$salida[] = algo($x)` — siempre | `array_map` |",
  "| `if (...) { $salida[] = $x; }` — a veces, y el elemento tal cual | `array_filter` |",
  "| `$suma = $suma + algo($x)` — un solo valor que crece | `array_reduce` |",
  "",
  "Y esa tabla se lee al revés también: si tu `foreach` no encaja en ninguna de las tres, es",
  "un `foreach` que se queda. No todo bucle es una de estas tres funciones.",
  "",
  "## Los tres, escritos",
  "",
  "```php",
  "return array_map(fn($n) => $n * 2, $numeros);",
  "return array_values(array_filter($numeros, fn($n) => $n % 2 === 0));",
  "return array_reduce($numeros, fn($llevado, $n) => $llevado + $n, 0);",
  "```",
  "",
  "Fíjate en el `array_values` del segundo: el `foreach` que rellenaba `$salida[]` iba poniendo",
  "las posiciones 0, 1, 2, y `array_filter` conserva las originales. Sin `array_values` el",
  "resultado tiene huecos en las claves y no es lo que había antes. Hay un test que lo",
  "comprueba, porque es el detalle que se escapa.",
  "",
  "## Lo que se gana, y lo que no",
  "",
  "Se gana: menos sitios donde equivocarse, y **el nombre dice qué pasa**. `array_map` promete",
  "que salen tantos como entran; `array_filter`, que los que salen son los mismos que entraron.",
  "Leyendo `foreach` hay que comprobarlo.",
  "",
  "No se gana velocidad. En PHP suelen ser algo más lentas que el bucle a mano, y da igual: la",
  "diferencia es inapreciable salvo en listas enormes, y ahí lo que hace falta es no tener la",
  "lista entera en memoria.",
  "",
  "## Cuándo se queda el `foreach`",
  "",
  "Tres casos, y son frecuentes:",
  "",
  "- **Cuando hay que salir a medias.** Un bucle con `break` porque ya encontraste lo que",
  "  buscabas no se puede escribir con estas. Existe una función para eso —buscar—, y si no,",
  "  `foreach` con `break` es lo honrado.",
  "- **Cuando se llevan dos cosas a la vez.** Un total y un nombre, un contador y una lista: el",
  "  acumulador tendría que ser un array con las dos, y a partir de ahí se lee peor.",
  "- **Cuando el cuerpo tiene efectos**: imprimir, escribir en un fichero, hablar por la red.",
  "  `array_map` con un cuerpo que imprime funciona y engaña: parece que transforma y lo que",
  "  hace es actuar.",
  "",
  "No es un premio usar la función más moderna. El objetivo es que se lea.",
  "",
  "## Pruébalo tú",
