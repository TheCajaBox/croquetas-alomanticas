  "var_dump(array_map(fn($n) => $n * 2, $numeros));",
  "var_dump(array_filter($numeros, fn($n) => $n % 2 === 0));          // mira las claves",
  "var_dump(array_values(array_filter($numeros, fn($n) => $n % 2 === 0)));",
  "var_dump(array_reduce($numeros, fn($ll, $n) => $ll + $n, 0));",
  "```",
