  "var_dump(array_reduce($sacos, fn($ll, $u) => $ll + $u, 10));   // 21",
  "var_dump(array_reduce([], fn($ll, $u) => $ll + $u, 10));       // 10",
  "var_dump(array_reduce([-5, -2], fn($ll, $u) => max($ll, $u), 0));   // 0, y no es el mayor",
  "```",
