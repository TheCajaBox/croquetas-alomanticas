  "const activo = false || true       // true  <- un false a propósito, machacado",
  "```",
  "",
  "Si la recompensa es de verdad cero, `||` la sustituye. Si el nombre está vacío a",
  "propósito, `||` lo cambia. Con `??` no pasa: solo actúa cuando de verdad no hay",
  "nada.",
  "",
  "```js",
  "const recompensa = 0 ?? 100        // 0",
  "const activo = false ?? true       // false",
  "```",
  "",
  "**La regla: `??` para valores por defecto, `||` solo cuando de verdad quieras",
  "tratar el cero y el vacío como «no hay».** Que es más raro de lo que parece.",
  "",
  "## Se combinan, y así es como se usa de verdad",
  "",
  "```js",
  "const ciudad = ficha?.direccion?.ciudad ?? 'desconocida'",
  "```",
  "",
