  "Los datos de verdad vienen incompletos. Una ficha sin alias, un caso sin agente",
  "asignado, un campo que el servidor no ha rellenado. Y hasta hace poco, protegerse",
  "de eso llenaba el código de comprobaciones.",
  "",
  "```js",
  "const ciudad = ficha && ficha.direccion && ficha.direccion.ciudad",
  "```",
  "",
  "Ahora hay dos operadores que hacen eso mismo, y bien.",
  "",
  "## El encadenamiento opcional: ?.",
  "",
  "```js",
  "const ciudad = ficha?.direccion?.ciudad",
  "```",
  "",
  "Se lee: «si `ficha` existe, dame su dirección; si esa existe, dame su ciudad».",
  "En cuanto uno de los pasos es `null` o `undefined`, **para ahí y devuelve",
  "`undefined`** en vez de reventar.",
  "",
  "Y funciona también con llamadas y con posiciones:",
  "",
  "```js",
  "objeto.metodo?.()        // llama solo si el método existe",
  "lista?.[0]               // accede solo si la lista existe",
  "```",
  "",
  "Lo que hay que tener claro es qué es exactamente lo que comprueba: **solo `null` y",
  "`undefined`**. Un `0`, un `''` o un `false` pasan por el `?.` sin problema, porque",
  "existen. Eso es lo correcto, aunque no coincide con lo que hace un `if` normal.",
  "",
  "## La coalescencia nula: ??",
  "",
  "```js",
  "const recompensa = ficha.recompensa ?? 0",
  "```",
  "",
  "«Si `ficha.recompensa` es `null` o `undefined`, usa 0; si no, usa lo que haya».",
  "",
  "Y ahora, la razón de que exista, que es la parte importante. Antes se hacía así:",
  "",
  "```js",
  "const recompensa = ficha.recompensa || 0",
  "```",
  "",
  "Y eso tiene un fallo que se cuela en producción todo el rato: `||` usa **los seis",
  "valores falsos**, no solo los vacíos.",
  "",
  "```js",
  "const recompensa = 0 || 100        // 100  <- el cero legítimo se pierde",
